    @Test fun `golden eval meets CT-9 top-1 and top-3 targets`() {
        assertTrue(golden.size >= 200, "CT-9 needs at least 200 pairs, found ${golden.size}")
        var top1 = 0
        var top3 = 0
        val misses = mutableListOf<String>()
        for (g in golden) {
            val ranking = ContactScorer.rank(candidates, listOf(g.spoken))
            val topIds = ranking.take(3).map { it.contactId }
            if (topIds.firstOrNull() == g.expectedId) top1++ else misses.add("top1 miss: spoken='${g.spoken}' expected=${g.expectedId} got=${topIds}")
            if (g.expectedId in topIds) top3++ else misses.add("top3 miss: spoken='${g.spoken}' expected=${g.expectedId} got=${topIds}")
        }
        val top1Rate = top1.toDouble() / golden.size
        val top3Rate = top3.toDouble() / golden.size
        val report = "top1=$top1/${golden.size} (%.3f) top3=$top3/${golden.size} (%.3f)".format(top1Rate, top3Rate)
        println("CT-9 golden eval: $report")
        assertTrue(top1Rate >= 0.90, "CT-9 top-1 below target: $report\n" + misses.joinToString("\n"))
        assertTrue(top3Rate >= 0.98, "CT-9 top-3 below target: $report\n" + misses.joinToString("\n"))
    }
